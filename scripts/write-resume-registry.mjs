import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";

const readExistingFile = async (filePath) => {
    try {
        return await readFile(filePath, "utf8");
    } catch (error) {
        if (error.code === "ENOENT") {
            return null;
        }

        throw error;
    }
};

const writeIfChanged = async (filePath, content) => {
    if (await readExistingFile(filePath) !== content) {
        await writeFile(filePath, content, "utf8");
    }
};

const createRegistry = (languages, variants) => {
    const imports = [
        ...languages.map(({ importPath }, index) => `import webResume${index} from "${importPath}";`),
        ...variants.map(({ importPath }, index) => `import pdfResume${index} from "${importPath}";`),
    ].join("\n");
    const webEntries = languages
        .map(({ locale }, index) => `    ${JSON.stringify(locale)}: webResume${index},`)
        .join("\n");
    const pdfEntries = variants
        .map((variant, index) => [
            "    {",
            `        includePhoto: ${variant.includePhoto},`,
            `        locale: ${JSON.stringify(variant.locale)},`,
            `        pages: ${variant.pages},`,
            `        slug: ${JSON.stringify(variant.slug)},`,
            `        route: ${JSON.stringify(variant.route)},`,
            `        fileName: ${JSON.stringify(variant.fileName)},`,
            `        sourceFile: ${JSON.stringify(variant.sourceFile)},`,
            `        resume: pdfResume${index},`,
            "    },",
        ].join("\n"))
        .join("\n");

    return `// Generated by scripts/discover-resumes.mjs.
import type { Resume } from "@/types/resume";
${imports}

export interface PdfResumeDefinition {
    includePhoto: boolean;
    locale: string;
    pages: number;
    slug: string;
    route: string;
    fileName: string;
    sourceFile: string;
    resume: Resume;
}

export const webResumes: Record<string, Resume> = {
${webEntries}
};

export const pdfResumeDefinitions: PdfResumeDefinition[] = [
${pdfEntries}
];

export const getPdfResumeDefinition = (locale: string, slug: string) =>
    pdfResumeDefinitions.find((definition) => definition.locale === locale && definition.slug === slug);
`;
};

export const writeResumeRegistry = async ({ dataDirectory, languages, variants }) => {
    const publicMetadata = variants.map(({ includePhoto, locale, pages, slug, fileName }) => ({
        includePhoto,
        locale,
        pages,
        slug,
        fileName,
    }));
    const manifestProfiles = variants.map(({ importPath, ...profile }) => profile);

    await Promise.all([
        writeIfChanged(
            path.join(dataDirectory, "resumeRegistry.generated.ts"),
            createRegistry(languages, variants),
        ),
        writeIfChanged(
            path.join(dataDirectory, "pdfResumeMetadata.generated.ts"),
            `// Generated by scripts/discover-resumes.mjs.\nexport const pdfResumeMetadata = ${JSON.stringify(publicMetadata, null, 4)} as const;\n`,
        ),
        writeIfChanged(
            path.join(dataDirectory, "pdf-resume-manifest.generated.json"),
            `${JSON.stringify(manifestProfiles, null, 2)}\n`,
        ),
    ]);
};
